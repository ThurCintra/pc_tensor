import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { quicktype, InputData, JSONSchemaInput, FetchingJSONSchemaStore } from 'quicktype-core';

const here = dirname(fileURLToPath(import.meta.url));
const schemaFile = join(here, '..', 'generated', 'protocol.schema.json');
const outFile = join(
  here,
  '..',
  '..',
  '..',
  'apps',
  'agent',
  'PcSentinel.Protocol',
  'Generated',
  'Protocol.cs',
);

const schemaJson = await readFile(schemaFile, 'utf8');

const schemaInput = new JSONSchemaInput(new FetchingJSONSchemaStore());
await schemaInput.addSource({ name: 'Protocol', schema: schemaJson });
const inputData = new InputData();
inputData.addInput(schemaInput);

const result = await quicktype({
  inputData,
  lang: 'csharp',
  rendererOptions: {
    namespace: 'PcSentinel.Protocol.Generated',
    framework: 'SystemTextJson',
    'csharp-version': '8',
  },
});

const header = `// <auto-generated>
// Generated from protocol.schema.json. Do not edit manually.
// Generator: quicktype-core (pinned via pnpm lockfile).
`;

let body = result.lines.join('\n');
// Normalize line endings and strip trailing whitespace for determinism.
body = body.replace(/\r\n/g, '\n').replace(/[ \t]+$/gm, '');
if (!body.endsWith('\n')) body += '\n';

await mkdir(dirname(outFile), { recursive: true });
await writeFile(outFile, `${header}${body}`, 'utf8');
console.log(`wrote ${outFile}`);
